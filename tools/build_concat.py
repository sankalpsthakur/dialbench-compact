#!/usr/bin/env python3
"""Concatenate source parts into one single-file Kaggle kernel script (kernels only upload their code_file).
usage: build_kernel.py KERNEL_DIR OUT_NAME PART [PART ...]
Parts are plain scripts/modules concatenated in order; they must not import each other."""
import sys, hashlib, os
kdir, out, *parts = sys.argv[1:]
hdr = ["# AUTO-GENERATED by tools/build_kernel.py - edit the parts, not this file."]
body = []
for p in parts:
    s = open(p).read()
    hdr.append(f"# part: {p} sha256={hashlib.sha256(s.encode()).hexdigest()[:16]}")
    body.append(f"\n# ======== {p} ========\n" + s)
open(os.path.join(kdir, out), "w").write("\n".join(hdr) + "\n" + "".join(body))
print("wrote", os.path.join(kdir, out), sum(len(b) for b in body), "bytes from", len(parts), "parts")
