#!/usr/bin/env python3
"""Bundle src modules + a main script into ONE Kaggle kernel file (kernels only upload their code_file).
Each module source is embedded as a string and exec'd into its own module (registered in sys.modules), so the
src files keep normal `from rpm_common import *` style imports and also run locally with src/ on sys.path.
usage: build_bundle.py KERNEL_DIR OUT_NAME --mods src/a.py src/b.py ... [--pre pre.py] --main main.py"""
import argparse, hashlib, os

ap = argparse.ArgumentParser()
ap.add_argument("kdir"); ap.add_argument("out")
ap.add_argument("--mods", nargs="*", default=[])
ap.add_argument("--pre", default=None, help="script text inserted BEFORE modules load (env vars, pip installs)")
ap.add_argument("--main", required=True)
a = ap.parse_args()
lines = ["# AUTO-GENERATED by tools/build_bundle.py - edit src/ and the main part, not this file.", "import sys, types"]
if a.pre:
    s = open(a.pre).read()
    lines.append(f"# pre: {a.pre} sha256={hashlib.sha256(s.encode()).hexdigest()[:16]}")
    lines.append(s)
lines.append("def _load(name, src):\n    m = types.ModuleType(name); m.__file__ = name + '.py'; sys.modules[name] = m\n    exec(compile(src, name + '.py', 'exec'), m.__dict__)")
for p in a.mods:
    s = open(p).read()
    name = os.path.splitext(os.path.basename(p))[0]
    lines.append(f"# module {name} from {p} sha256={hashlib.sha256(s.encode()).hexdigest()[:16]}")
    lines.append(f"_load({name!r}, {s!r})")
m = open(a.main).read()
lines.append(f"# main: {a.main} sha256={hashlib.sha256(m.encode()).hexdigest()[:16]}")
lines.append(m)
open(os.path.join(a.kdir, a.out), "w").write("\n".join(lines) + "\n")
print("wrote", os.path.join(a.kdir, a.out), len("\n".join(lines)), "bytes;", len(a.mods), "modules")
